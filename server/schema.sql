CREATE TABLE IF NOT EXISTS users (
 id UUID PRIMARY KEY, name TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'customer' CHECK(role IN ('customer','admin')),
 email_verified BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash TEXT PRIMARY KEY, user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS email_tokens (
 token_hash TEXT PRIMARY KEY, user_id UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value JSONB NOT NULL);
CREATE TABLE IF NOT EXISTS systems (id TEXT PRIMARY KEY, data JSONB NOT NULL);
CREATE TABLE IF NOT EXISTS requests (
 id UUID PRIMARY KEY, user_id UUID REFERENCES users(id), name TEXT NOT NULL, email TEXT NOT NULL,
 phone TEXT NOT NULL DEFAULT '', business TEXT NOT NULL, type TEXT NOT NULL, model TEXT NOT NULL DEFAULT '',
 description TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'Novo', notes TEXT NOT NULL DEFAULT '',
 consent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS requests_user_idx ON requests(user_id);
CREATE TABLE IF NOT EXISTS orders (
 transaction TEXT PRIMARY KEY, email TEXT NOT NULL, product_id TEXT NOT NULL,
 subscription_code TEXT, status TEXT NOT NULL, valid_until TIMESTAMPTZ NOT NULL,
 event_date BIGINT NOT NULL, auto_renew BOOLEAN NOT NULL DEFAULT TRUE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS orders_email_idx ON orders(email);
CREATE TABLE IF NOT EXISTS webhook_events (id TEXT PRIMARY KEY, event TEXT NOT NULL, processed_at TIMESTAMPTZ NOT NULL DEFAULT NOW());
CREATE TABLE IF NOT EXISTS subscription_cancellations (code TEXT PRIMARY KEY, product_id TEXT NOT NULL, email TEXT NOT NULL, event_date BIGINT NOT NULL);
